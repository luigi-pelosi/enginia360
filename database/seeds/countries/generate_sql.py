#!/usr/bin/env python3
"""Reproduce the canonical SQL offline using only the Python standard library."""
import argparse
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]


def render_sql(rows):
    allowed = set(re.findall(r'"([A-Z]{2})"',
        (ROOT / 'backend/Modules/Geography/CountryCodes.cs').read_text(encoding='utf-8')))
    seen = set()
    values = []
    for row in sorted(rows, key=lambda item: item['iso_code']):
        code, name = row['iso_code'], row['name']
        if code not in allowed or code in seen or not isinstance(name, str) or not name.strip():
            raise ValueError('Expected unique official ISO alpha-2 codes and nonempty names')
        seen.add(code)
        values.append("    ('" + name.replace("'", "''") + "', '" + code + "')")
    if not values:
        raise ValueError('Country dataset must not be empty')
    return ('-- Generated by database/seeds/countries/generate_sql.py. Do not edit.\n'
            '-- Italian names: pinned Unicode CLDR, Unicode-3.0 (see countries/).\n'
            '-- Insert missing ISO countries only. Existing rows remain untouched.\n'
            'INSERT INTO foundation.country (name, iso_code) VALUES\n'
            + ',\n'.join(values) + '\nON CONFLICT (iso_code) DO NOTHING;\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check canonical SQL without writing')
    parser.add_argument('--output', type=Path, default=HERE.parent / 'countries.sql')
    args = parser.parse_args()
    rows = json.loads((HERE / 'countries.json').read_text(encoding='utf-8'))
    if len(rows) != 249:
        parser.error('Expected exactly 249 countries')
    source = render_sql(rows)
    if args.check:
        if not args.output.is_file() or args.output.read_bytes() != source.encode('utf-8'):
            parser.exit(1, 'Country SQL differs from the canonical dataset\n')
        print('OK: canonical SQL matches 249 countries')
    else:
        args.output.write_bytes(source.encode('utf-8'))
        print(f'Generated {args.output} (249 countries)')


if __name__ == '__main__':
    main()
